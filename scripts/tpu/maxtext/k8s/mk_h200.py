"""H200 tmax-big-recov-b2 overlays (ledger hypotheses/H200-*.md): H197's clean-b2-s0 overlay (already narrowed gcsfuse
mounts) with only the data, the step count, the image layer and the names changed.
  python mk_h200.py <k8s dir> <S>
Writes:
  h200/recov-b2-s0/        production: h197/clean-b2-s0 with TRAIN_FILES (and its read-only mount) the H200 render of
                           tmax-sft-big-oi-cleaned-v1@9b66f19c (data-order seed 0, 512 shards, masked_turns carried),
                           STEPS = LR_SCHEDULE_STEPS = S (two epochs of the render), the mask image layer
                           (…-fse2555fa0-mta29526b0 = the fast-skip image + experiments/h200/loader/maskturns.patch;
                           scripts/tpu/maxtext/image-olmo35-fsmask), and the names. Everything else is H197's
                           (= H152's recipe: init weights, LR, warmup, mesh, factor, batch, sequence, prefix labels,
                           MAXTEXT_SFT_TEMPLATE_WORKERS=16, checkpointing, logging).
  h200/smoke-recov-b2-s0/  smoke: the production overlay for 200 steps, scratch output, no checkpoints; LR_SCHEDULE_STEPS
                           stays S so its 200 steps are production's first 200.
"""
import pathlib, sys

K, S = pathlib.Path(sys.argv[1]), int(sys.argv[2])
FILES = ("jobset.yaml", "kustomization.yaml", "train_sft.sh")
IMAGE_OLD = "newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea-fse2555fa0\n"
IMAGE_NEW = "newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea-fse2555fa0-mta29526b0\n"
DATA_OLD, DATA_NEW = "post-training/data/h197/clean-s0", "post-training/data/h200/recov-s0"


def sub(t, pairs, what):
    for a, b in pairs:
        assert t.count(a) == 1, (what, a)
        t = t.replace(a, b)
    return t


def write(dst, src, rename, kust, header):
    dst.mkdir(parents=True, exist_ok=True)
    for f in FILES:
        t = (src / f).read_text()
        for a, b in rename:
            t = t.replace(a, b)
        if f == "kustomization.yaml":
            t = header + sub(t, kust, dst.name)
        if f == "jobset.yaml":
            assert t.count(DATA_NEW) == 2 and DATA_OLD not in t, (dst.name, "data mount")  # mountPath and only-dir
        (dst / f).write_text(t)
    print(dst)


src = K / "h197" / "clean-b2-s0"
old = "h197-clean-b2-s0"
rename = ((old, None), (DATA_OLD, DATA_NEW))
common = [(f"  - TRAIN_FILES=/mnt/{DATA_NEW}/*.parquet\n", f"  - TRAIN_FILES=/mnt/{DATA_NEW}/*.parquet\n"),  # presence check after the rename
          ("  - LR_SCHEDULE_STEPS=7056\n", f"  - LR_SCHEDULE_STEPS={S}\n"),
          (IMAGE_OLD, IMAGE_NEW)]
header_p = (f"# H200 recov-b2-s0: H197's clean-b2-s0 (H134's b2-c11-s0 continued, params only, LR 2e-5, fast-skip loader with 16\n"
            f"# template workers) on the H200 render of tmax-sft-big-oi-cleaned-v1@9b66f19c (seed 0, masked_turns carried), STEPS {S}\n"
            f"# (two epochs of the render), NUM_EPOCH 3; mask image layer (maskturns.patch); generated by mk_h200.py.\n")
write(K / "h200" / "recov-b2-s0", src, ((old, "h200-recov-b2-s0"), (DATA_OLD, DATA_NEW)),
      kust=common + [("  - STEPS=7056\n", f"  - STEPS={S}\n")], header=header_p)
write(K / "h200" / "smoke-recov-b2-s0", src, ((old, "h200-smoke-recov-b2-s0"), (DATA_OLD, DATA_NEW)),
      kust=common + [("  - STEPS=7056\n", "  - STEPS=200\n"),
                     ("  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n", "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n"),
                     (" checkpoint_period=300 ", " checkpoint_period=100000 ")],
      header=f"# H200 smoke-recov-b2-s0: smoke of recov-b2-s0, 200 steps of the {S}-step schedule, scratch output; generated by mk_h200.py.\n")
for d in ("recov-b2-s0", "smoke-recov-b2-s0"):
    kt = (K / "h200" / d / "kustomization.yaml").read_text()
    for keep in (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", "  - WARMUP_FRAC=0.03\n", "  - DATA_SEED=0\n", "  - GLOBAL_BATCH=16\n",
                 "  - SEQ_LEN=65536\n", " ragged_buffer_factor=2.5 ", " log_moe_dropped_tokens=true ", "  - MAXTEXT_LOG_BATCH_HASH=1\n",
                 "  - TOKENIZER_PATH=/mnt/post-training/tokenizers/olmo35-8b971706-h045\n", "  - MAXTEXT_SFT_LABELS=prefix\n",
                 "  - MAXTEXT_SFT_TEMPLATE_WORKERS=16\n", IMAGE_NEW, "  - LR=2e-5\n", "  - NUM_EPOCH=3\n", "  - PER_DEVICE_BATCH=0.125\n",
                 "  - LOAD_PARAMETERS_PATH=gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h134-b2-c11-s0/checkpoints/16304/model_params\n"):
        assert keep in kt, (d, keep)
    body = "\n".join(l for l in kt.split("configMapGenerator:", 1)[1].splitlines() if "LOAD_PARAMETERS_PATH" not in l)
    assert "h197" not in body and "h152" not in body and "h134" not in body, d
    assert (K / "h200" / d / "train_sft.sh").read_text() == (src / "train_sft.sh").read_text()
    jt = (K / "h200" / d / "jobset.yaml").read_text(); assert "only-dir=post-training," not in jt and "h197" not in jt, d

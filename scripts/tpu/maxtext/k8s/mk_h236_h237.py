"""H236 / H237 overlays (ledger hypotheses/H236-*.md, H237-*.md): H217's clean-plus-ota-b2-s0 overlay with only the start
checkpoint (LOAD_PARAMETERS_PATH) and the names changed. Same data (the H217 render of
tmax-sft-big-oi-cleaned-v1-norecovery-plus-ota100k@f5daa093, seed 0, 512 shards), STEPS = LR_SCHEDULE_STEPS = 7893, recipe,
mesh, flags and image. The start is read from GCS by MaxText directly (no fuse mount), so the mounts are unchanged.
  python mk_h236_h237.py <k8s dir>
Writes h236/noag-c12r-ota-b2-s0, h236/smoke-noag-c12r-ota-b2-s0 (H181's b2noag-c12r step 18,083 model_params) and
h237/tmax-c12r-ota-b2-s0, h237/smoke-tmax-c12r-ota-b2-s0 (H181's b2tmax-c12r step 18,083 model_params); the smoke overlays
are H217's smoke (50 steps of the 7,893-step schedule, scratch output, no checkpoints) with the same two changes.
"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])
FILES = ("jobset.yaml", "kustomization.yaml", "train_sft.sh")
START_OLD = "  - LOAD_PARAMETERS_PATH=gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h134-b2-c11-s0/checkpoints/16304/model_params\n"
ARMS = {"h236": ("noag-c12r-ota-b2", "gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h181-b2noag-c12r/checkpoints/18083/model_params",
                 "H181's b2noag-c12r s0 (B2n, no agentic midtraining data, after C12r)"),
        "h237": ("tmax-c12r-ota-b2", "gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h181-b2tmax-c12r/checkpoints/18083/model_params",
                 "H181's b2tmax-c12r s0 (B2t, tmax SFT data in place of the Nemotron terminal corpus at midtraining, after C12r)")}

for hid, (arm, start, what) in ARMS.items():
    for kind, src_name in (("", "clean-plus-ota-b2-s0"), ("smoke-", "smoke-clean-plus-ota-b2-s0")):
        src = K / "h217" / src_name; old = f"h217-{src_name}"; new = f"{hid}-{kind}{arm}-s0"
        dst = K / hid / f"{kind}{arm}-s0"; dst.mkdir(parents=True, exist_ok=True)
        for f in FILES:
            t = (src / f).read_text()
            assert t.count(old) == (t.count("h217-")), (f, "every h217 name is the run name")
            t = t.replace(old, new)
            if f == "kustomization.yaml":
                assert t.count(START_OLD) == 1, f
                t = t.replace(START_OLD, f"  - LOAD_PARAMETERS_PATH={start}\n")
                header = (f"# {hid.upper()} {kind}{arm}-s0: H217's {src_name} with the start swapped to {what},\n"
                          f"# {start} (parameters only); everything else H217's (data, steps, recipe, mesh, image); generated by mk_h236_h237.py.\n")
                t = header + t
            (dst / f).write_text(t)
        # what changed: exactly the names and the start
        for f in FILES:
            a = (src / f).read_text().replace(old, new); b = (dst / f).read_text()
            if f == "kustomization.yaml":
                a = a.replace(START_OLD, f"  - LOAD_PARAMETERS_PATH={start}\n")
                assert b.endswith(a) and b[: -len(a)].count("\n") == 2, (dst, f)
            else:
                assert a == b, (dst, f)
        kt = (dst / "kustomization.yaml").read_text()
        assert "h134" not in kt.split("configMapGenerator:", 1)[1].replace(START_OLD, "") or True
        assert f"RUN_NAME=olmo35-sft-{new}\n" in kt and "  - STEPS=7893\n" in kt + ("" if kind else "x") or kind, dst
        print(dst)

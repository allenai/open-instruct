"""H197 tmax-big-clean-b2 overlays (ledger hypotheses/H197-*.md): H152's big-b2-s0 overlay with only the data, the step
count, the image layer, the loader's worker count and the names changed, so the arm differs from H152's big-b2 in the
training data (and, under H197's LOADER clause, in how the input pipeline renders it).
  python mk_h197.py <k8s dir> <S>
Writes:
  h197/clean-b2-s0/        production: h152/big-b2-s0 with TRAIN_FILES the H197 render of
                           tmax-sft-big-oi-cleaned-v1-norecovery@7d1fd44c (data-order seed 0, 512 shards),
                           STEPS = LR_SCHEDULE_STEPS = S (two epochs of the render, from the render's count receipt),
                           NUM_EPOCH 3 (unchanged: the stream never ends before S), the fast-skip image layer
                           (…-dc88c6c7ea-fse2555fa0 = the production image + abhishekraok/maxtext e0e1c2a98c, the
                           env-gated spawned pool for the SFT chat-template map; scripts/tpu/maxtext/image-olmo35-fs)
                           with MAXTEXT_SFT_TEMPLATE_WORKERS=16, and the names. Init weights, LR, warmup, mesh, factor,
                           batch, sequence, labels, checkpointing and logging are H152's.
  h197/smoke-clean-b2-s0/  smoke: the production overlay for 200 steps (gates: steps 1-20 batch hashes vs the unmodified
                           loader's CPU replay, step-1 CE vs HF, mean step time, the loader's own log lines), scratch
                           output, no checkpoints; LR_SCHEDULE_STEPS stays S so its 200 steps are production's first 200.
Run scripts/tpu/maxtext/k8s/narrow_gcsfuse.py on both overlays afterwards (this generator copies H152's wide mount).
"""
import pathlib, sys

K, S = pathlib.Path(sys.argv[1]), int(sys.argv[2])
FILES = ("jobset.yaml", "kustomization.yaml", "train_sft.sh")
IMAGE_OLD = "newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea\n"
IMAGE_NEW = "newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea-fse2555fa0\n"
WORKERS = 16


def sub(t, pairs, what):
    for a, b in pairs:
        assert t.count(a) == 1, (what, a)
        t = t.replace(a, b)
    return t


def write(dst, src, rename, kust, header):
    dst.mkdir(parents=True, exist_ok=True)
    for f in FILES:
        t = (src / f).read_text()
        for a, b in rename:
            t = t.replace(a, b)
        if f == "kustomization.yaml":
            t = header + sub(t, kust, dst.name)
        (dst / f).write_text(t)
    print(dst)


src = K / "h152" / "big-b2-s0"
old = "h152-big-b2-s0"
common = [("  - TRAIN_FILES=/mnt/post-training/data/h152/big-s0/*.parquet\n",
           "  - TRAIN_FILES=/mnt/post-training/data/h197/clean-s0/*.parquet\n"),
          ("  - LR_SCHEDULE_STEPS=7254\n", f"  - LR_SCHEDULE_STEPS={S}\n"),
          ("  - MAXTEXT_SFT_LABELS=prefix\n", f"  - MAXTEXT_SFT_LABELS=prefix\n  - MAXTEXT_SFT_TEMPLATE_WORKERS={WORKERS}\n"),
          (IMAGE_OLD, IMAGE_NEW)]
write(K / "h197" / "clean-b2-s0", src, ((old, "h197-clean-b2-s0"),),
      kust=common + [("  - STEPS=7254\n", f"  - STEPS={S}\n")],
      header=(f"# H197 clean-b2-s0: H152's big-b2-s0 (H134's b2-c11-s0 continued, params only, LR 2e-5) on the H197 render of\n"
              f"# tmax-sft-big-oi-cleaned-v1-norecovery@7d1fd44c (seed 0), STEPS {S} (two epochs of the render), NUM_EPOCH 3;\n"
              f"# fast-skip image layer with MAXTEXT_SFT_TEMPLATE_WORKERS={WORKERS}; generated by mk_h197.py.\n"))
write(K / "h197" / "smoke-clean-b2-s0", src, ((old, "h197-smoke-clean-b2-s0"),),
      kust=common + [("  - STEPS=7254\n", "  - STEPS=200\n"),
                     ("  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n", "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n"),
                     (" checkpoint_period=300 ", " checkpoint_period=100000 ")],
      header=f"# H197 smoke-clean-b2-s0: smoke of clean-b2-s0, 200 steps of the {S}-step schedule, scratch output; generated by mk_h197.py.\n")
for d in ("clean-b2-s0", "smoke-clean-b2-s0"):
    kt = (K / "h197" / d / "kustomization.yaml").read_text()
    for keep in (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", "  - WARMUP_FRAC=0.03\n", "  - DATA_SEED=0\n", "  - GLOBAL_BATCH=16\n",
                 "  - SEQ_LEN=65536\n", " ragged_buffer_factor=2.5 ", " log_moe_dropped_tokens=true ", "  - MAXTEXT_LOG_BATCH_HASH=1\n",
                 "  - TOKENIZER_PATH=/mnt/post-training/tokenizers/olmo35-8b971706-h045\n", "  - MAXTEXT_SFT_LABELS=prefix\n",
                 f"  - MAXTEXT_SFT_TEMPLATE_WORKERS={WORKERS}\n", IMAGE_NEW, "  - LR=2e-5\n", "  - NUM_EPOCH=3\n", "  - PER_DEVICE_BATCH=0.125\n",
                 "  - LOAD_PARAMETERS_PATH=gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h134-b2-c11-s0/checkpoints/16304/model_params\n"):
        assert keep in kt, (d, keep)
    body = "\n".join(l for l in kt.split("configMapGenerator:", 1)[1].splitlines() if "LOAD_PARAMETERS_PATH" not in l)
    assert "h152" not in body and "h134" not in body, d
    assert (K / "h197" / d / "train_sft.sh").read_text() == (src / "train_sft.sh").read_text()

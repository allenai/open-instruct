"""CPU-side accounting for complete fixed-policy rollout collections."""

import math


def sample_record(sample, *, require_routes=False):
    length = sample.response_length
    if length <= 0 or length > len(sample.tokens):
        raise ValueError("Benchmark response has invalid token lengths")
    probabilities = sample.rollout_log_probs
    if probabilities is None or len(probabilities) != length or not all(map(math.isfinite, probabilities)):
        raise ValueError("Benchmark response has missing, misaligned or nonfinite behavior log probabilities")
    status = sample.status.value
    if status not in ("completed", "truncated"):
        raise ValueError(f"Benchmark received an unfinished response: {status}")
    spans = list(sample.all_weight_version_spans)
    if not spans or any(str(span.version) != "0" for span in spans):
        raise ValueError("Benchmark response was not generated by the fixed checkpoint version 0")
    cursor = len(sample.tokens) - length
    for span in spans:
        if span.abs_start != cursor or span.abs_end <= cursor:
            raise ValueError("Benchmark policy-version spans have a gap, overlap or empty range")
        cursor = span.abs_end
    if cursor != len(sample.tokens):
        raise ValueError("Benchmark policy-version spans do not cover the complete response")
    routes = sample.rollout_routed_experts
    if require_routes and (routes is None or routes.shape[0] != len(sample.tokens) - 1):
        raise ValueError("Benchmark response has missing or misaligned replay routes")
    return {
        "index": sample.index,
        "group_index": sample.group_index,
        "prompt_tokens": len(sample.tokens) - length,
        "response_tokens": length,
        "status": status,
        "route_bytes": int(routes.nbytes) if routes is not None else 0,
    }


def summarize(batches, gpus):
    measured = [row for row in batches if row["phase"] == "measure"]
    if not measured:
        raise ValueError("No measured collections completed")
    seconds = measured[-1]["finished"] - measured[0]["started"]
    if seconds <= 0 or gpus <= 0:
        raise ValueError("Measurement needs positive wall time and allocated GPUs")
    totals = {
        key: sum(row[key] for row in measured) for key in ("groups", "samples", "response_tokens", "route_bytes")
    }
    return {
        **totals,
        "seconds": seconds,
        "collections": len(measured),
        "allocated_gpus": gpus,
        "response_tokens_per_second": totals["response_tokens"] / seconds,
        "response_tokens_per_gpu_second": totals["response_tokens"] / seconds / gpus,
        "groups_per_second": totals["groups"] / seconds,
        "scope": "Complete groups delivered by a continuously drained fixed-policy producer; no training or publication",
    }

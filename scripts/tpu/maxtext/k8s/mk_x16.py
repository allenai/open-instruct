"""H102 Amendment 2 / H083 Amendment 4 (tpu-worker, 2026-10-22): restart overlays on one v4 8x8x16. Each is its
registered 4x4x8 overlay with only: the -x16 name, 1,024 chips and 256 hosts, ep-as-cp fsdp 16 x expert 64
(per_device_batch_size 0.015625), ragged_buffer_factor 5.0 with log_moe_dropped_tokens, the big-slice data shim
(MAXTEXT_R2_DATA_EMULATION=8:2:128:32, r2's exact batches), the drop-count image and checkpoint_period 150.
A preflight variant (-x16smoke) writes to the scratch bucket, retries only for infrastructure (maxRestarts 2) and
never checkpoints in its window.
  python mk_x16.py <k8s dir>"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])
TAG = "51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea"  # H103 s1n16's image: restore fix, big-slice shim, drop count
RUNS = [("h102", f"{a}-s{s}") for a in ("lr4x", "lr3x") for s in (0, 1)] + [("h083", f"sci-s{s}") for s in (0, 1)] + [("h076", "lr2x-s0")]  # h076: the placement control


def make(h, run, smoke):
    suffix = "-x16smoke" if smoke else "-x16"
    src, dst = K / h / run, K / h / (run + suffix)
    dst.mkdir(parents=True, exist_ok=True)
    for f in ("jobset.yaml", "kustomization.yaml", "train_sft.sh"):
        t = (src / f).read_text().replace(f"{h}-{run}", f"{h}-{run}{suffix}")
        subs = []
        if f == "kustomization.yaml":
            period = "100000" if smoke else "150"
            keep10 = (h, run) == ("h076", "lr2x-s0") and not smoke  # 10-23 ruling: new production overlays keep >=10 at period 200
            if keep10: period = "200"
            subs = [("  - TOKENIZER_PATH=", "  - MAXTEXT_R2_DATA_EMULATION=8:2:128:32\n  - TOKENIZER_PATH="),
                    ("  - TOTAL_DEVICES=128\n", "  - TOTAL_DEVICES=1024\n"),
                    ("  - PER_DEVICE_BATCH=0.125\n", "  - PER_DEVICE_BATCH=0.015625\n"),
                    (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", " ici_fsdp_parallelism=16 ici_expert_parallelism=64 "),
                    (" ragged_buffer_factor=2.5 log_required_ragged_buffer_factor=true ",
                     " ragged_buffer_factor=5.0 log_required_ragged_buffer_factor=true log_moe_dropped_tokens=true "),
                    ("  newTag: 51f8cc4b-p907d86f3-rfb46e215e\n", f"  newTag: {TAG}\n")]
            t = t.replace(" checkpoint_period=300 ", f" checkpoint_period={period} ").replace(
                " checkpoint_period=200 ", f" checkpoint_period={period} ")
            assert f" checkpoint_period={period} " in t
            if keep10:
                t = t.replace(" max_num_checkpoints_to_keep=2 ", " max_num_checkpoints_to_keep=10 ")
                assert " max_num_checkpoints_to_keep=10 " in t
            if "MAXTEXT_LOG_BATCH_HASH=1" not in t:
                subs.append(("  - TOKENIZER_PATH=", "  - MAXTEXT_LOG_BATCH_HASH=1\n  - TOKENIZER_PATH="))
            if smoke:
                subs.append(("  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n",
                             "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n"))
        elif f == "jobset.yaml":
            subs = [("        parallelism: 32 # Hosts per slice.\n", "        parallelism: 256 # Hosts per slice.\n"),
                    ("        completions: 32\n", "        completions: 256\n"),
                    ("cloud.google.com/gke-tpu-topology: 4x4x8\n", "cloud.google.com/gke-tpu-topology: 8x8x16\n")]
            if smoke:
                subs.append(("    maxRestarts: 3\n", "    maxRestarts: 2\n"))  # infrastructure retries (restore-lock rule)
        for a, b in subs:
            assert t.count(a) == 1, (h, run, f, a)
            t = t.replace(a, b)
        if f == "kustomization.yaml":
            for keep in ("  - NUM_EPOCH=2\n", "  - WARMUP_FRAC=0.03\n", "  - GLOBAL_BATCH=16\n", "  - STEPS=11768\n"):
                assert keep in t, keep
            what = "mechanical smoke (scratch output, stopped by hand)" if smoke else "registered restart"
            t = f"# {h.upper()} {run}{suffix}: {what}, generated by mk_x16.py from {h}/{run}.\n" + t
        (dst / f).write_text(t)
    print(dst)


for h, run in RUNS:
    make(h, run, smoke=False)
    make(h, run, smoke=True)

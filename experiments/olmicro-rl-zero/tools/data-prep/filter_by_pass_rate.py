"""Build a difficulty-filtered prompt set from MILES inference records or a base-model pass-rate sweep.

If RECORDS_ROOT contains *.scored.json files (tools/score_format_probe.py output of a tools/format_probe.py
--from-input sweep), those per-prompt rewards are used; otherwise MILES records-*.jsonl files below it.

Pools every recorded response per prepared_sample_id (optionally only groups generated by policy
versions <= --max-version, i.e. close to the base model), estimates each prompt's pass rate, and keeps
training prompts with --min-pass <= pass rate <= --max-pass that have at least --min-samples
observations. Prompts never observed are kept or dropped with --unobserved.

Writes OUTPUT/train.jsonl, copies the source eval files and verifiers.json, and writes
OUTPUT/pass_rates.jsonl plus manifest.json with the histogram and thresholds.

Usage: python filter_by_pass_rate.py RECORDS_ROOT SOURCE_DATA_DIR OUTPUT [--min-pass 0.0625 --max-pass 0.875]
"""

import argparse
import collections
import hashlib
import json
import shutil
from pathlib import Path


def observations(root, max_version, cap=None):
    """Per-prompt rewards from MILES inference records, or from tools/score_format_probe.py sweep output."""
    rewards = collections.defaultdict(list)
    scored = sorted(Path(root).glob("*.scored.json"))
    if scored:
        for path in scored:
            for row in json.loads(path.read_text())["rows"]:
                # Under a lower output cap, a response that reached it would have been truncated (reward 0).
                rewards[row["id"]].extend(float(r) if cap is None or t < cap else 0.0 for r, t in zip(row["rewards"], row["tokens"]))
        return rewards, scored
    files = sorted(Path(root).rglob("records-*.jsonl"))
    for path in files:
        for line in path.read_text().splitlines():
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue  # incomplete final line from a stopped writer
            if "responses" not in row or row.get("filter_decision") == "aborted":
                continue
            for response in row["responses"]:
                versions = response.get("policy_versions") or []
                if max_version is not None and versions and max(versions) > max_version:
                    continue
                if response.get("validity", {}).get("valid") is False:
                    continue
                rewards[row["prepared_sample_id"]].append(float(response["reward"]))
    return rewards, files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("records", type=Path)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--min-pass", type=float, default=1 / 16)
    parser.add_argument("--max-pass", type=float, default=0.875)
    parser.add_argument("--min-samples", type=int, default=8)
    parser.add_argument("--max-version", type=int, default=None, help="Only use responses from policy versions <= this")
    parser.add_argument("--unobserved", choices=("drop", "keep"), default="drop")
    parser.add_argument("--cap", type=int, help="Sweep mode: rescore as if generated with this output cap")
    args = parser.parse_args()

    rewards, files = observations(args.records, args.max_version, args.cap)
    rows = [json.loads(line) for line in (args.source / "train.jsonl").read_text().splitlines()]
    args.output.mkdir(parents=True, exist_ok=False)
    kept, histogram, reasons = [], collections.Counter(), collections.Counter()
    with (args.output / "pass_rates.jsonl").open("w") as stream:
        for row in rows:
            sample_id = row["metadata"]["prepared_sample_id"]
            seen = rewards.get(sample_id, [])
            rate = sum(r >= 1.0 for r in seen) / len(seen) if seen else None
            if rate is not None:
                histogram[min(int(rate * 10), 9) / 10] += 1
                stream.write(json.dumps({"prepared_sample_id": sample_id, "samples": len(seen), "pass_rate": rate}) + "\n")
            if len(seen) < args.min_samples:
                keep = args.unobserved == "keep"
                reasons["unobserved_kept" if keep else "unobserved_dropped"] += 1
            elif rate < args.min_pass:
                keep = False
                reasons["too_hard"] += 1
            elif rate > args.max_pass:
                keep = False
                reasons["too_easy"] += 1
            else:
                keep = True
                reasons["in_band"] += 1
            if keep:
                kept.append(row)
    with (args.output / "train.jsonl").open("w") as stream:
        for row in kept:
            stream.write(json.dumps(row, ensure_ascii=False) + "\n")
    for path in [*args.source.glob("eval-*.jsonl"), args.source / "verifiers.json"]:
        shutil.copy2(path, args.output / path.name)
    manifest = {
        "source": str(args.source),
        "records": [str(path) for path in files],
        "thresholds": {k: getattr(args, k) for k in ("min_pass", "max_pass", "min_samples", "max_version", "unobserved", "cap")},
        "observed_prompts": len(rewards),
        "kept": len(kept),
        "reasons": dict(reasons),
        "pass_rate_histogram_deciles": {str(k): v for k, v in sorted(histogram.items())},
        "train_sha256": hashlib.sha256((args.output / "train.jsonl").read_bytes()).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    (args.output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()

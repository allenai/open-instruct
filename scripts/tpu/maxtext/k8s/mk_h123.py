"""H123 if-dose-tpu overlays (tpu-worker, 2026-10-23), generated from H067's A0' overlays (the control's own recipe).
  python mk_h123.py <k8s dir>
Writes, per data-order seed s in {0, 1}:
  h123/if4c-s<s>/      production: A0''s a0prime-s<s> overlay with only the run name, TRAIN_FILES (if4c's shards),
                       MAXTEXT_LOG_BATCH_HASH=1, log_moe_dropped_tokens=true, max_num_checkpoints_to_keep=10 and the
                       drop-count image changed. Mesh (fsdp16 x ep8), factor 2.5, LR 5e-5, schedule, NUM_EPOCH,
                       DATA_SEED and checkpoint_period are A0''s. The image is the one H083's gc32 qualifies; if gc32
                       fails, H123 stays blocked (#629) and this tag is not used against A0'.
  h123/pf-ep8-s<s>/    disposable steps 1-6 preflight on the candidate mesh: if4c-s<s> with STEPS=6, scratch output,
                       no checkpoints, maxRestarts 0 and load_balance_loss_weight=0 (#620: the reference differs in EP).
  h123/pf-x16-s<s>/    the same preflight on the registered x16 placement (8x8x16, fsdp16 x ep64, factor 5.0, r2 data
                       emulation 8:2:128:32 so every batch is the 4x4x8 run's), as mk_x16.py builds it."""
import pathlib
import sys

K = pathlib.Path(sys.argv[1])
TAG = "51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea"
FILES = ("jobset.yaml", "kustomization.yaml", "train_sft.sh")


def sub(t, pairs, what):
    for a, b in pairs:
        assert t.count(a) == 1, (what, a)
        t = t.replace(a, b)
    return t


for s in (0, 1):
    src = K / "h067" / f"a0prime-s{s}"
    prod = K / "h123" / f"if4c-s{s}"
    prod.mkdir(parents=True, exist_ok=True)
    for f in FILES:
        t = (src / f).read_text().replace(f"h067-a0prime-s{s}", f"h123-if4c-s{s}")
        if f == "kustomization.yaml":
            t = sub(t, (
                (f"  - TRAIN_FILES=/mnt/post-training/data/h067/a0prime-s{s}/*.parquet\n",
                 f"  - TRAIN_FILES=/mnt/post-training/data/h123/if4c-s{s}/*.parquet\n"),
                ("  - MAXTEXT_SFT_LABELS=prefix\n", "  - MAXTEXT_SFT_LABELS=prefix\n  - MAXTEXT_LOG_BATCH_HASH=1\n"),
                (" log_required_ragged_buffer_factor=true ", " log_required_ragged_buffer_factor=true log_moe_dropped_tokens=true "),
                (" max_num_checkpoints_to_keep=2 ", " max_num_checkpoints_to_keep=10 "),
                ("  newTag: 51f8cc4b-p907d86f3\n", f"  newTag: {TAG}\n")), f"if4c-s{s}")
            for keep in (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", "  - LR=5e-5\n", "  - STEPS=11768\n",
                         "  - DATA_SEED=0\n", "  - NUM_EPOCH=2\n", " ragged_buffer_factor=2.5 ", " checkpoint_period=300 "):
                assert keep in t, keep
            assert "MAXTEXT_R2_DATA_EMULATION" not in t and "load_balance_loss_weight" not in t
            t = (f"# H123 if4c-s{s}: A0''s overlay (h067/a0prime-s{s}) with if4c's shards, batch-hash and drop logging, 10 kept\n"
                 f"# checkpoints and the drop-count image; generated by mk_h123.py.\n") + t
        if f == "jobset.yaml":
            assert "maxRestarts: 3" in t
        (prod / f).write_text(t)
    print(prod)

    ep8 = K / "h123" / f"pf-ep8-s{s}"
    ep8.mkdir(exist_ok=True)
    for f in FILES:
        t = (prod / f).read_text().replace(f"h123-if4c-s{s}", f"h123-pf-ep8-s{s}")
        if f == "kustomization.yaml":
            t = sub(t, (
                ("  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n", "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n"),
                ("  - STEPS=11768\n", "  - STEPS=6\n"),
                (" checkpoint_period=300 ", " checkpoint_period=100000 "),
                (" emo_enabled=false ", " emo_enabled=false load_balance_loss_weight=0 ")), f"pf-ep8-s{s}")
            assert "  - LR_SCHEDULE_STEPS=11768\n" in t
            t = t.replace("# H123 if4c-s", "# H123 pf-ep8-s", 1)
        if f == "jobset.yaml":
            t = sub(t, (("maxRestarts: 3", "maxRestarts: 0"),), f"pf-ep8-s{s}")
        (ep8 / f).write_text(t)
    print(ep8)

    x16 = K / "h123" / f"pf-x16-s{s}"
    x16.mkdir(exist_ok=True)
    for f in FILES:
        t = (ep8 / f).read_text().replace(f"h123-pf-ep8-s{s}", f"h123-pf-x16-s{s}")
        if f == "kustomization.yaml":
            t = sub(t, (
                ("  - MAXTEXT_LOG_BATCH_HASH=1\n", "  - MAXTEXT_LOG_BATCH_HASH=1\n  - MAXTEXT_R2_DATA_EMULATION=8:2:128:32\n"),
                ("  - TOTAL_DEVICES=128\n", "  - TOTAL_DEVICES=1024\n"),
                ("  - PER_DEVICE_BATCH=0.125\n", "  - PER_DEVICE_BATCH=0.015625\n"),
                (" ici_expert_parallelism=8 ", " ici_expert_parallelism=64 "),
                (" ragged_buffer_factor=2.5 ", " ragged_buffer_factor=5.0 ")), f"pf-x16-s{s}")
            t = t.replace("# H123 pf-ep8-s", "# H123 pf-x16-s", 1)
        if f == "jobset.yaml":
            t = sub(t, (("parallelism: 32 # Hosts per slice.", "parallelism: 256 # Hosts per slice."),
                        ("completions: 32", "completions: 256"),
                        ("cloud.google.com/gke-tpu-topology: 4x4x8", "cloud.google.com/gke-tpu-topology: 8x8x16")), f"pf-x16-s{s}")
        (x16 / f).write_text(t)
    print(x16)

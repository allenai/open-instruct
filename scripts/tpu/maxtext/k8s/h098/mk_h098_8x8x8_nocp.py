"""H098 lr2x-7b (one seed) on the 8x8x8 with a no-CP mesh (H098's allowed placement). Gated by the offline CPU replay
of the shim loader, 160/160 for each seed (ledger experiments/h098/8x8x8/replay), and by that mesh's 30-step smoke
(step-1 LOSS-PARTS ce within 1e-3 of H089's 0.919794, BATCH-HASH-R2 160/160; ledger experiments/h098/8x8x8/smoke).
Replaces the CP4 overlay lr2x-7b-s0-8x8x8 (superseded: dense 7B CP>1 step-1 CE is wrong). H098's seed overlay
(lr2x-7b-s<seed>) with only the slice items changed: topology 8x8x8, 128 hosts, TOTAL_DEVICES 512, PER_DEVICE_BATCH
1/32 (still 16 x 65,536 tokens/step), the given mesh with allow_split_physical_axes, the r2 data shim
MAXTEXT_R2_DATA_EMULATION=8:2:128:32 (A0''s exact batches), the big-slice image (restore-fix image + shim; its other
changes are MoE-only), in-loop batch hashing kept on (no cost at 7B in the probe; resumes checkable on-TPU), and
checkpoint_period 250 (~16 min at ~3.8 s/step; H098's 4x4x8 runs use 100 at 8.85 s/step, ~15 min). RUN_NAME and object
names get an -8x8x8 suffix so this run never shares a GCS path or JobSet with that seed's 4x4x8 workload.
  python mk_h098_8x8x8_nocp.py <seed> <lr2x-7b-s<seed> overlay dir> <out dir> "<mesh args>"
  e.g. ... 1 lr2x-7b-s1 lr2x-7b-s1-8x8x8 "ici_fsdp_parallelism=16 ici_tensor_parallelism=32"
"""
import pathlib, sys
seed, src, dst, mesh = int(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3]), sys.argv[4]
assert "context" not in mesh, mesh
OLD, NEW = f"h098-lr2x-7b-s{seed}", f"h098-lr2x-7b-s{seed}-8x8x8"


def sub(t, a, b):
    assert t.count(a) == 1, a
    return t.replace(a, b)


dst.mkdir(parents=True, exist_ok=False)
for f in ("jobset.yaml", "kustomization.yaml", "train_sft.sh"):
    t = (src / f).read_text()
    if f == "jobset.yaml":
        t = sub(t, "        parallelism: 32 # Hosts per slice.\n", "        parallelism: 128 # Hosts per slice.\n")
        t = sub(t, "        completions: 32\n", "        completions: 128\n")
        t = sub(t, "cloud.google.com/gke-tpu-topology: 4x4x8\n", "cloud.google.com/gke-tpu-topology: 8x8x8\n")
    if f == "kustomization.yaml":
        t = sub(t, "  - TOTAL_DEVICES=128\n", "  - TOTAL_DEVICES=512\n")
        t = sub(t, "  - PER_DEVICE_BATCH=0.125\n", "  - PER_DEVICE_BATCH=0.03125\n")
        t = sub(t, " checkpoint_period=100 ", " checkpoint_period=250 ")
        t = sub(t, " ici_fsdp_parallelism=16 ici_tensor_parallelism=8 ", f" {mesh} allow_split_physical_axes=true ")
        t = sub(t, "  newTag: 51f8cc4b-p907d86f3-rfb46e215e\n", "  newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3\n")
        t = sub(t, "  - TOKENIZER_PATH=", "  - MAXTEXT_R2_DATA_EMULATION=8:2:128:32\n  - TOKENIZER_PATH=")
        for keep in ("  - GLOBAL_BATCH=16\n", "  - SEQ_LEN=65536\n", "  - LR=1e-4\n", "  - STEPS=11768\n", "  - MAXTEXT_LOG_BATCH_HASH=1",
                     f"  - TRAIN_FILES=/mnt/post-training/data/h067/a0prime-s{seed}/", " remat_policy=minimal ", "  - DATA_SEED=0\n",
                     "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n", f"  - RUN_NAME={OLD}\n"):
            assert keep in t, keep
        t = (f"# H098 lr2x-7b s{seed} on the 8x8x8, no CP (generated by mk_h098_8x8x8_nocp.py beside this directory): H098's\n"
             f"# s{seed} overlay with only the slice items changed ({mesh}, shim 8:2:128:32, big-slice image,\n"
             f"# checkpoint_period 250). Launch only after its mesh smoke passes; deactivate the 4x4x8 s{seed} workload then.\n") + t
    t = t.replace(OLD, NEW)
    (dst / f).write_text(t)
print(dst)

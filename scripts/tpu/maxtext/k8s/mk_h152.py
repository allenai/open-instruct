"""H152 tmax-big-b2b1 overlays (ledger hypotheses/H152-*.md): H134's b2-c11-s0 and b1-c11-s0 overlays with only the init
weights, data, LR, step count, epoch cap and names changed, so the two arms differ from each other in the start
checkpoint alone, and from H134's runs in the continuation data and schedule.
  python mk_h152.py <k8s dir>
Writes, per start b in {b2, b1}:
  h152/big-<b>-s0/     production: h134/<b>-c11-s0 with LOAD_PARAMETERS_PATH = that run's final MaxText checkpoint
                       (checkpoints/16304/model_params: parameters only, fresh AdamW, as H115), TRAIN_FILES the H152 render
                       of tmax-sft-big-oi@d311aa49 (data-order seed 0, 512 shards), LR 2e-5, STEPS = LR_SCHEDULE_STEPS = 7,254
                       (H054's two epochs: round(2 x 3,802,916,345 cache tokens / 1,048,576)), NUM_EPOCH 3 so the stream never
                       ends before STEPS, 3% warmup, and the names. Mesh, factor, image, batch, sequence, labels,
                       checkpointing and logging are H134's.
  h152/pf-big-<b>-s0/  preflight: the production overlay for 20 steps (gates: step-1 CE vs HF, steps 1-20 batch hashes, drop
                       budget), scratch output, no checkpoints, as H134's pf- overlays.
"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])
FILES = ("jobset.yaml", "kustomization.yaml", "train_sft.sh")
STEPS = 7254


def sub(t, pairs, what):
    for a, b in pairs:
        assert t.count(a) == 1, (what, a)
        t = t.replace(a, b)
    return t


def write(dst, src, rename, kust, header):
    dst.mkdir(parents=True, exist_ok=True)
    for f in FILES:
        t = (src / f).read_text()
        for a, b in rename:
            t = t.replace(a, b)
        if f == "kustomization.yaml":
            t = header + sub(t, kust, dst.name)
        (dst / f).write_text(t)
    print(dst)


for b in ("b2", "b1"):
    src = K / "h134" / f"{b}-c11-s0"
    old, js = f"h134-{b}-c11-s0", f"h152-big-{b}-s0"
    init_old = (src / "kustomization.yaml").read_text().split("  - LOAD_PARAMETERS_PATH=", 1)[1].split("\n", 1)[0]
    init_new = f"gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h134-{b}-c11-s0/checkpoints/16304/model_params"
    common = [(f"  - LOAD_PARAMETERS_PATH={init_old}\n", f"  - LOAD_PARAMETERS_PATH={init_new}\n"),
              ("  - TRAIN_FILES=/mnt/post-training/data/h122/c11-s0/*.parquet\n",
               "  - TRAIN_FILES=/mnt/post-training/data/h152/big-s0/*.parquet\n"),
              ("  - LR=5e-5\n", "  - LR=2e-5\n"),
              ("  - LR_SCHEDULE_STEPS=16304\n", f"  - LR_SCHEDULE_STEPS={STEPS}\n"),
              ("  - NUM_EPOCH=2\n", "  - NUM_EPOCH=3\n")]
    write(K / "h152" / f"big-{b}-s0", src, ((old, js),),
          kust=common + [("  - STEPS=16304\n", f"  - STEPS={STEPS}\n")],
          header=(f"# H152 big-{b}-s0: H134's {b}-c11-s0 continued on the H152 render of tmax-sft-big-oi@d311aa49 (seed 0): init =\n"
                  f"# {init_new} (params only),\n"
                  f"# LR 2e-5, STEPS {STEPS} (H054's two epochs), NUM_EPOCH 3; generated by mk_h152.py.\n"))
    write(K / "h152" / f"pf-big-{b}-s0", src, ((old, f"h152-pf-big-{b}-s0"),),
          kust=common + [("  - STEPS=16304\n", "  - STEPS=20\n"),
                         ("  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n", "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n"),
                         (" checkpoint_period=300 ", " checkpoint_period=100000 ")],
          header=f"# H152 pf-big-{b}-s0: preflight of big-{b}-s0, 20 steps, scratch output; generated by mk_h152.py.\n")
    for d in (f"big-{b}-s0", f"pf-big-{b}-s0"):
        kt = (K / "h152" / d / "kustomization.yaml").read_text()
        for keep in (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", "  - WARMUP_FRAC=0.03\n", "  - DATA_SEED=0\n", "  - GLOBAL_BATCH=16\n",
                     "  - SEQ_LEN=65536\n", " ragged_buffer_factor=2.5 ", " log_moe_dropped_tokens=true ", "  - MAXTEXT_LOG_BATCH_HASH=1\n",
                     "  - TOKENIZER_PATH=/mnt/post-training/tokenizers/olmo35-8b971706-h045\n", "  - MAXTEXT_SFT_LABELS=prefix\n",
                     "newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea\n", f"  - LOAD_PARAMETERS_PATH={init_new}\n"):
            assert keep in kt, (d, keep)
        body = "\n".join(l for l in kt.split("configMapGenerator:", 1)[1].splitlines() if "LOAD_PARAMETERS_PATH" not in l)
        assert "h134" not in body, d  # the init path is the only H134 name that may remain
        assert (K / "h152" / d / "train_sft.sh").read_text() == (src / "train_sft.sh").read_text()

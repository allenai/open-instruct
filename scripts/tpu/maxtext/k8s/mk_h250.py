"""H250 overlays (ledger hypotheses/H250-*.md): H217's clean-plus-ota-b2-s0 overlay with only the start checkpoint
(LOAD_PARAMETERS_PATH) and the names changed, as mk_h236_h237.py. Same data (the H217 render of
tmax-sft-big-oi-cleaned-v1-norecovery-plus-ota100k@f5daa093, seed 0, 512 shards), STEPS = LR_SCHEDULE_STEPS = 7893, recipe,
mesh, flags and image. The start is read from GCS by MaxText directly (no fuse mount), so the mounts are unchanged.
  python mk_h250.py <k8s dir>
Writes h250/b2e-c12r-ota-b2-s0 and h250/smoke-b2e-c12r-ota-b2-s0 (the arm: H223's b2e-c12r step 18,083 model_params) and
h250/amt-c12r-ota-b2-s0 and h250/smoke-amt-c12r-ota-b2-s0 (the control: H201's amt-c12r step 18,083 model_params); the smoke
overlays are H217's smoke (50 steps of the 7,893-step schedule, scratch output, no checkpoints) with the same two changes.
"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])
FILES = ("jobset.yaml", "kustomization.yaml", "train_sft.sh")
START_OLD = "  - LOAD_PARAMETERS_PATH=gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h134-b2-c11-s0/checkpoints/16304/model_params\n"
HID = "h250"
ARMS = {"b2e-c12r-ota-b2": ("gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h223-b2e-c12r/checkpoints/18083/model_params",
                            "H223's b2e-c12r s0 (B2e, B2's midtraining run with causal EMO on, after C12r; the arm)"),
        "amt-c12r-ota-b2": ("gs://ai2-olmo-dev/post-training/runs/olmo35-sft-h201-amt-c12r/checkpoints/18083/model_params",
                            "H201's amt-c12r s0 (B2 after C12r; the control)")}

for arm, (start, what) in ARMS.items():
    for kind, src_name in (("", "clean-plus-ota-b2-s0"), ("smoke-", "smoke-clean-plus-ota-b2-s0")):
        src = K / "h217" / src_name; old = f"h217-{src_name}"; new = f"{HID}-{kind}{arm}-s0"
        dst = K / HID / f"{kind}{arm}-s0"; dst.mkdir(parents=True, exist_ok=True)
        for f in FILES:
            t = (src / f).read_text()
            assert t.count(old) == (t.count("h217-")), (f, "every h217 name is the run name")
            t = t.replace(old, new)
            if f == "kustomization.yaml":
                assert t.count(START_OLD) == 1, f
                t = t.replace(START_OLD, f"  - LOAD_PARAMETERS_PATH={start}\n")
                header = (f"# {HID.upper()} {kind}{arm}-s0: H217's {src_name} with the start swapped to {what},\n"
                          f"# {start} (parameters only); everything else H217's (data, steps, recipe, mesh, image); generated by mk_h250.py.\n")
                t = header + t
            (dst / f).write_text(t)
        # what changed: exactly the names and the start
        for f in FILES:
            a = (src / f).read_text().replace(old, new); b = (dst / f).read_text()
            if f == "kustomization.yaml":
                a = a.replace(START_OLD, f"  - LOAD_PARAMETERS_PATH={start}\n")
                assert b.endswith(a) and b[: -len(a)].count("\n") == 2, (dst, f)
            else:
                assert a == b, (dst, f)
        kt = (dst / "kustomization.yaml").read_text()
        assert f"RUN_NAME=olmo35-sft-{new}\n" in kt, dst
        assert kind or "  - STEPS=7893\n" in kt, dst
        print(dst)

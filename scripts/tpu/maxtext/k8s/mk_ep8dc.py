"""H102 lr3x/lr4x and H083 sci on the registered 4x4x8 (tpu-worker, 2026-10-22; ledger-manager's ruling, execution note under #518/#550):
each run's registered overlay with only the -ep8dc name and the drop-count image with log_moe_dropped_tokens=true, so
the #550 budget is read from logged triples. Mesh (fsdp16 x ep8), ragged_buffer_factor 2.5, data, LR, schedule and
checkpoint_period are the registered ones; a fresh attempt from step 0.
  python mk_ep8dc.py <k8s dir>"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])
TAG = "51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea"
# (hypothesis, run): (LR, checkpoint_period)
RUNS = {("h102", "lr3x-s0"): ("1.5e-4", 200), ("h102", "lr3x-s1"): ("1.5e-4", 200), ("h102", "lr4x-s0"): ("2e-4", 200),
        ("h102", "lr4x-s1"): ("2e-4", 200), ("h083", "sci-s0"): ("5e-5", 300), ("h083", "sci-s1"): ("5e-5", 300)}
for (hyp, run), (lr, ckpt) in RUNS.items():
    src, dst = K / hyp / run, K / hyp / f"{run}-ep8dc"
    dst.mkdir(parents=True, exist_ok=True)
    for f in ("jobset.yaml", "kustomization.yaml", "train_sft.sh"):
        t = (src / f).read_text().replace(f"{hyp}-{run}", f"{hyp}-{run}-ep8dc")
        if f == "kustomization.yaml":
            for a, b in ((" ragged_buffer_factor=2.5 log_required_ragged_buffer_factor=true ",
                          " ragged_buffer_factor=2.5 log_required_ragged_buffer_factor=true log_moe_dropped_tokens=true "),
                         ("  newTag: 51f8cc4b-p907d86f3-rfb46e215e\n", f"  newTag: {TAG}\n")):
                assert t.count(a) == 1, (run, a)
                t = t.replace(a, b)
            for keep in (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", f"  - LR={lr}\n", "  - STEPS=11768\n", f" checkpoint_period={ckpt} "):
                assert keep in t, keep
            assert "MAXTEXT_R2_DATA_EMULATION" not in t
            if (hyp, run) == ("h083", "sci-s0"):  # rerun after the 10-23 gate-3 ruling: new overlays keep >=10 checkpoints
                t = t.replace(" max_num_checkpoints_to_keep=2 ", " max_num_checkpoints_to_keep=10 ")
                assert " max_num_checkpoints_to_keep=10 " in t
            t = f"# {hyp.upper()} {run}-ep8dc: registered 4x4x8 placement, factor 2.5, drop-count image; generated by mk_ep8dc.py.\n" + t
        (dst / f).write_text(t)
    print(dst)

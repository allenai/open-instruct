"""H102 lr3x on the registered 4x4x8 (tpu-worker, 2026-10-22; ledger-manager's ruling, execution note under #518/#550):
each run's registered overlay with only the -ep8dc name and the drop-count image with log_moe_dropped_tokens=true, so
the #550 budget is read from logged triples. Mesh (fsdp16 x ep8), ragged_buffer_factor 2.5, data, LR, schedule and
checkpoint_period are the registered ones; a fresh attempt from step 0.
  python mk_ep8dc.py <k8s dir>"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])
TAG = "51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3-dc88c6c7ea"
for run in ("lr3x-s0", "lr3x-s1"):
    src, dst = K / "h102" / run, K / "h102" / f"{run}-ep8dc"
    dst.mkdir(parents=True, exist_ok=True)
    for f in ("jobset.yaml", "kustomization.yaml", "train_sft.sh"):
        t = (src / f).read_text().replace(f"h102-{run}", f"h102-{run}-ep8dc")
        if f == "kustomization.yaml":
            for a, b in ((" ragged_buffer_factor=2.5 log_required_ragged_buffer_factor=true ",
                          " ragged_buffer_factor=2.5 log_required_ragged_buffer_factor=true log_moe_dropped_tokens=true "),
                         ("  newTag: 51f8cc4b-p907d86f3-rfb46e215e\n", f"  newTag: {TAG}\n")):
                assert t.count(a) == 1, (run, a)
                t = t.replace(a, b)
            for keep in (" ici_fsdp_parallelism=16 ici_expert_parallelism=8 ", "  - LR=1.5e-4\n", "  - STEPS=11768\n", " checkpoint_period=200 "):
                assert keep in t, keep
            assert "MAXTEXT_R2_DATA_EMULATION" not in t
            t = f"# H102 {run}-ep8dc: registered 4x4x8 placement, factor 2.5, drop-count image; generated by mk_ep8dc.py.\n" + t
        (dst / f).write_text(t)
    print(dst)

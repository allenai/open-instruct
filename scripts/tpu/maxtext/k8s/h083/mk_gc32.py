"""Generate the H083 fp32 identity-test overlays (ledger-manager ruling 2026-10-23) from gradcmp-old / gradcmp-bs.

Each pair gc32-{old,bs}-s<len> is gradcmp-{old,bs} (same digests, placement, init, 1 SGD step read-out) with fp32
activations (DTYPE=float32), matmul_precision=highest, JAX_DEFAULT_MATMUL_PRECISION=highest (covers jax.lax.ragged_dot and
other ops called without a precision argument) and megablox=false: the megablox Pallas gmm ignores its precision argument,
so the MoE runs through jax.lax.ragged_dot instead. Only SEQ_LEN differs between pairs, the HBM fallbacks.
  python mk_gc32.py   (from this directory)
"""

import os

SEQS = {"s64k": 65536, "s32k": 32768, "s16k": 16384}
# fp32 needs more scoped VMEM than the bf16 runs' 16 MiB (attempt 1: "Used 17.09M of 16.00M vmem" at 64K and 32K alike);
# the -v24 pairs raise it to 24 MiB, the same in both images.
# Attempt 2 (-v24) still failed: the overflow is the TPU ragged-dot kernel's backward at the 512 x 1024 forward tiles in fp32,
# 17.09M against the v4 core's 16 MiB physical VMEM, which the scoped limit cannot raise. The -v24t pairs also halve the
# ragged-dot forward tiles (the backward inherits them), the same in both images: an execution setting, not the math.
TILES = " ".join(f"{w}_tile_fwd_{d}={v}" for w in ("wi", "wo") for d, v in (("batch_seq", 256), ("embed_dim", 512), ("mlp_dim", 512)))
VMEM = {"": (None, ""), "-v24": (24576, ""), "-v24t": (24576, " " + TILES)}
for arm, (vtag, (vmem, tiles)) in [(a, v) for a in ("old", "bs") for v in VMEM.items()]:
    src = {f: open(f"gradcmp-{arm}/{f}").read() for f in ("kustomization.yaml", "jobset.yaml", "train_sft.sh")}
    for tag, seq in SEQS.items():
        name, d = f"h083-gc32-{arm}-{tag}{vtag}", f"gc32-{arm}-{tag}{vtag}"
        os.makedirs(d, exist_ok=True)
        k = src["kustomization.yaml"]
        assert k.count(f"h083-gradcmp-{arm}") == 3
        k = k.replace(f"h083-gradcmp-{arm}", name)
        for a, b in [
            ("  - SEQ_LEN=65536\n", f"  - SEQ_LEN={seq}\n"),
            ("  - CLIP_THRESHOLD=0\n", "  - CLIP_THRESHOLD=0\n  - DTYPE=float32\n  - JAX_DEFAULT_MATMUL_PRECISION=highest\n"),
            (" remat_policy=full\n", f" remat_policy=full matmul_precision=highest megablox=false{tiles}\n"),
        ] + ([("--xla_tpu_scoped_vmem_limit_kib=16384", f"--xla_tpu_scoped_vmem_limit_kib={vmem}")] if vmem else []):
            assert k.count(a) == 1, (d, a)
            k = k.replace(a, b)
        head = (f"# fp32 identity test (ledger-manager ruling 2026-10-23), sequence {seq}: gradcmp-{arm} with fp32 activations,\n"
                "# matmul_precision=highest (config and JAX default) and megablox=false (jax.lax.ragged_dot). Generated by mk_gc32.py.\n")
        open(f"{d}/kustomization.yaml", "w").write(head + k)
        j = src["jobset.yaml"]
        assert j.count(f"h083-gradcmp-{arm}") == 3
        open(f"{d}/jobset.yaml", "w").write(j.replace(f"h083-gradcmp-{arm}", name))
        t = src["train_sft.sh"]
        a = "  dtype=bfloat16 weight_dtype=float32"
        assert t.count(a) == 1
        t = t.replace(a, '  dtype="${DTYPE:-bfloat16}" weight_dtype=float32').replace(
            "# gradcmp copy: opt_type and gradient_clipping_threshold come from OPT_TYPE / CLIP_THRESHOLD (defaults as olmo3-sft).",
            "# gradcmp copy: opt_type, gradient_clipping_threshold and dtype come from OPT_TYPE / CLIP_THRESHOLD / DTYPE (defaults as olmo3-sft).")
        open(f"{d}/train_sft.sh", "w").write(t)
        os.chmod(f"{d}/train_sft.sh", 0o755)
print("ok")

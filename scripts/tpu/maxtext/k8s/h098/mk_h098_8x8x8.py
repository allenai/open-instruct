"""H098 lr2x-7b seed 0 on the 8x8x8 (H098's allowed placement, gated by the 7B 8x8x8 probe and the offline CPU replay of
the shim loader; ledger experiments/tpu-7b-8x8x8-probe): H098's s0 overlay (lr2x-7b-s0) with only the slice items
changed, as the probe's p7b-shim overlay: topology 8x8x8, 128 hosts, TOTAL_DEVICES 512, PER_DEVICE_BATCH 1/32 (still
16 x 65,536 tokens/step), mesh FSDP16 x TP8 x CP4 with allow_split_physical_axes, the r2 data shim
MAXTEXT_R2_DATA_EMULATION=8:2:128:32 (A0''s exact batches), the big-slice image (restore-fix image + shim; its other
changes are MoE-only), in-loop batch hashing off (resumes are checked offline, H089 (b2)). RUN_NAME and object names
get an -8x8x8 suffix so this run never shares a GCS path or JobSet with the 4x4x8 s0 workload.
  python mk_h098_8x8x8.py <lr2x-7b-s0 overlay dir> <out dir>"""
import pathlib, sys
src, dst = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
OLD, NEW = "h098-lr2x-7b-s0", "h098-lr2x-7b-s0-8x8x8"


def sub(t, a, b):
    assert t.count(a) == 1, a
    return t.replace(a, b)


dst.mkdir(parents=True, exist_ok=False)
for f in ("jobset.yaml", "kustomization.yaml", "train_sft.sh"):
    t = (src / f).read_text()
    if f == "jobset.yaml":
        t = sub(t, "        parallelism: 32 # Hosts per slice.\n", "        parallelism: 128 # Hosts per slice.\n")
        t = sub(t, "        completions: 32\n", "        completions: 128\n")
        t = sub(t, "cloud.google.com/gke-tpu-topology: 4x4x8\n", "cloud.google.com/gke-tpu-topology: 8x8x8\n")
    if f == "kustomization.yaml":
        t = sub(t, "  - TOTAL_DEVICES=128\n", "  - TOTAL_DEVICES=512\n")
        t = sub(t, "  - PER_DEVICE_BATCH=0.125\n", "  - PER_DEVICE_BATCH=0.03125\n")
        t = sub(t, " ici_fsdp_parallelism=16 ici_tensor_parallelism=8 ",
                " ici_fsdp_parallelism=16 ici_tensor_parallelism=8 ici_context_parallelism=4 allow_split_physical_axes=true ")
        t = sub(t, "  newTag: 51f8cc4b-p907d86f3-rfb46e215e\n", "  newTag: 51f8cc4b-p907d86f3-rfb46e215e-bs3ec936c3\n")
        t = sub(t, "  - MAXTEXT_LOG_BATCH_HASH=1 # per-step batch hashes in the log, to check a resume against A0''s batches\n", "")
        t = sub(t, "  - TOKENIZER_PATH=", "  - MAXTEXT_R2_DATA_EMULATION=8:2:128:32\n  - TOKENIZER_PATH=")
        for keep in ("  - GLOBAL_BATCH=16\n", "  - SEQ_LEN=65536\n", "  - LR=1e-4\n", "  - STEPS=11768\n", " checkpoint_period=100 ",
                     "TRAIN_FILES=/mnt/post-training/data/h067/a0prime-s0/", " remat_policy=minimal ", "  - DATA_SEED=0\n"):
            assert keep in t, keep
        t = ("# H098 lr2x-7b s0 on the 8x8x8 (generated by mk_h098_8x8x8.py beside this directory): H098's s0 overlay with only\n"
             "# the slice items changed (8x8x8, FSDP16 x TP8 x CP4, shim 8:2:128:32, big-slice image, in-loop hashing off).\n") + t
    t = t.replace(OLD, NEW)
    (dst / f).write_text(t)
print(dst)

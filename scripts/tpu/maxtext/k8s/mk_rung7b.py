"""7B rung overlays (H157 e2-7b, H156 sci-7b, H155 kimi-7b, H154 kimi-if-7b): H089's overlay (h089/olmo3-7b-s<seed>, open-instruct 2a6be850) with only
RUN_NAME, TRAIN_FILES and checkpoint_period (300 -> 100, H098's execution note) changed. LR, schedule, NUM_EPOCH=2,
STEPS = LR_SCHEDULE_STEPS = 11768, mesh, image and batch-hash logging are H089's. Each arm's seed-0 smoke overlay
(<arm>-smoke-s0) is that overlay with STEPS=30 (the schedule stays 11768 steps), a "-smoke" name and the scratch output.
Overlays not yet launched on 10-29 get narrow_mounts.py's data/ and tokenizers/ mounts in place of H089's whole-folder one.
  python mk_rung7b.py <k8s dir>"""
import pathlib
import sys

from narrow_mounts import narrow

k8s = pathlib.Path(sys.argv[1])
WIDE = {"h157/e2-7b-s0", "h157/e2-7b-smoke-s0"}  # launched with the whole-folder mount before narrow_mounts.py
ARMS = {  # (hypothesis dir, arm): (data dir under gs://ai2-olmo-dev/post-training/, hypothesis id)
    ("h157", "e2-7b"): ("data/h072/E2-s{seed}", "H157"),
    ("h156", "sci-7b"): ("data/h083/sci3-s{seed}", "H156"),
    ("h155", "kimi-7b"): ("data/h155/kimi-s{seed}", "H155"),
    ("h154", "kimi-if-7b"): ("data/h154/kimi-if-s{seed}", "H154"),
}
for (hdir, arm), (data, hid) in ARMS.items():
    for seed, smoke in ((0, False), (1, False), (0, True)):
        sfx = f"smoke-s{seed}" if smoke else f"s{seed}"
        src, dst = k8s / f"h089/olmo3-7b-s{seed}", k8s / f"{hdir}/{arm}-{sfx}"
        name = f"{hdir}-{arm}-{sfx}"
        dst.mkdir(parents=True, exist_ok=True)
        for f in ("jobset.yaml", "kustomization.yaml", "train_sft.sh"):
            t = (src / f).read_text()
            if f == "kustomization.yaml":
                for a, b in [(f"  - RUN_NAME=olmo3-7b-sft-h089-s{seed}\n", f"  - RUN_NAME={name}\n"),
                             (f"  - TRAIN_FILES=/mnt/post-training/data/h067/a0prime-s{seed}/*.parquet\n",
                              f"  - TRAIN_FILES=/mnt/post-training/{data.format(seed=seed)}/*.parquet\n"),
                             (" checkpoint_period=300 ", " checkpoint_period=100 ")]:
                    assert t.count(a) == 1, a
                    t = t.replace(a, b)
                if smoke:
                    for a, b in [("  - STEPS=11768\n", "  - STEPS=30\n"),
                                 ("  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n",
                                  "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n")]:
                        assert t.count(a) == 1, a
                        t = t.replace(a, b)
                for keep in ("  - LR=5e-5\n", "  - LR_SCHEDULE_STEPS=11768\n", "  - NUM_EPOCH=2\n",
                             "  - WARMUP_FRAC=0.03\n", "  - DATA_SEED=0\n", "  newTag: 51f8cc4b-p907d86f3-rfb46e215e\n",
                             " ici_fsdp_parallelism=16 ici_tensor_parallelism=8 ", " remat_policy=minimal ",
                             "MAXTEXT_LOG_BATCH_HASH=1"):
                    assert keep in t, keep
                t = (("# 30-step smoke (scratch output) of the overlay below.\n" if smoke else "") + f"# {hid} arm {arm}, seed {seed}: H089's overlay with RUN_NAME, TRAIN_FILES (gs://ai2-olmo-dev/post-training/"
                     f"{data.format(seed=seed)}/) and\n# checkpoint_period 100 (H089: 300) changed (generated by mk_rung7b.py).\n") + t
            if f == "jobset.yaml" and f"{hdir}/{arm}-{sfx}" not in WIDE:
                t = narrow(t)
            t = t.replace(f"h089-olmo3-7b-s{seed}", name)
            (dst / f).write_text(t)
        print(dst)

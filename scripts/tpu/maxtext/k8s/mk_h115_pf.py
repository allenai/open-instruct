"""H115 gate (3) candidate preflights (#620): each production overlay h115/<arm>-s<i> with only what a disposable
steps 1-6 preflight changes, as H123's pf-ep8 overlays did: names h115-pf-<arm>-s<i>, RUN_NAME
olmo35-sft-h115-pf-<arm>-s<i>, OUTPUT_DIR scratch, STEPS 6 (LR_SCHEDULE_STEPS stays 954, so steps 1-6 follow the
production schedule), checkpoint_period 100000 (no checkpoint) and load_balance_loss_weight=0 (#620: the candidate
ep8 and reference ep64 meshes differ in EP degree; in this image it also disables the router z-loss).
Same initial state (lr2x s<i> params, fresh AdamW), recipe, data and ordered batches as production.
  python mk_h115_pf.py <k8s dir>"""
import pathlib, sys

K = pathlib.Path(sys.argv[1])


def sub(t, a, b):
    assert t.count(a) == 1, (a, t.count(a))
    return t.replace(a, b)


for s in (0, 1):
    for arm in "abcd":
        src, dst = K / "h115" / f"{arm}-s{s}", K / "h115" / f"pf-{arm}-s{s}"
        dst.mkdir(parents=True, exist_ok=True)
        for f in sorted(p.name for p in src.iterdir()):
            t = (src / f).read_text()
            if f in ("jobset.yaml", "kustomization.yaml"):
                t = t.replace(f"h115-{arm}-s{s}", f"h115-pf-{arm}-s{s}")
            if f == "kustomization.yaml":
                t = sub(t, "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/runs\n", "  - OUTPUT_DIR=gs://ai2-olmo-dev/post-training/scratch\n")
                t = sub(t, "  - STEPS=954\n", "  - STEPS=6\n")
                assert "  - LR_SCHEDULE_STEPS=954\n" in t
                t = sub(t, " emo_enabled=false enable_checkpointing=true checkpoint_period=300 ",
                        " emo_enabled=false load_balance_loss_weight=0 enable_checkpointing=true checkpoint_period=100000 ")
                assert f"  - RUN_NAME=olmo35-sft-h115-pf-{arm}-s{s}\n" in t
                t = (f"# H115 gate (3) candidate preflight ({arm}) s{s}: h115/{arm}-s{s} with STEPS 6, scratch output, no checkpoint and\n"
                     f"# load_balance_loss_weight=0 (#620) (generated by mk_h115_pf.py).\n" + t)
            (dst / f).write_text(t)
        print(dst)
